SYNTHETIC_SPEECH_NOTICE = (
    "This localized media may contain synthetic speech generated by software. Identity-preserving speech, "
    "where present, was produced only under the speaker's recorded consent. For academic, non-commercial "
    "demonstration only (third-party model licences)."
)


class ExportRefused(ValidationError):
    pass


def _snapshot_objects(approval):
    scenes = approval.snapshot["scenes"]
    t_ids = [i for s in scenes for i in s["translation_ids"]]
    s_ids = [i for s in scenes for i in s["synthesised_segment_ids"]]
    r_ids = [s["render_id"] for s in scenes]
    return (SegmentTranslation.objects.filter(pk__in=t_ids), SynthesisedSegment.objects.filter(pk__in=s_ids),
            RenderedScene.objects.filter(pk__in=r_ids))


def export_problems(approval):
    """Why export is refused (empty = allowed)."""
    problems = []
    if approval.status != approval.Status.VALID:
        problems.append("The approval is no longer valid.")
    translations, synths, renders = _snapshot_objects(approval)
    video = approval.localization.project.videos.first()
    mock = []
    if video and video.transcript_is_mock:
        mock.append("transcript")
    if translations.filter(is_mock=True).exists():
        mock.append("translations")
    if synths.filter(is_mock=True).exists():
        mock.append("speech")
    if renders.filter(is_mock=True).exists():
        mock.append("previews")
    if mock:
        # Hard rule (ADR 0005): export is refused if any artefact in the snapshot came from a mock.
        problems.append("The approved version contains MOCK output (" + ", ".join(mock) + "). Mock output can never be exported.")
    if synths.exclude(status="ACTIVE").exists() or renders.exclude(status="ACTIVE").exists():
        problems.append("Some approved artefacts were quarantined or purged.")
    problems.extend(_consent_problems(approval))
    return problems


def _consent_problems(approval):
    """CP9: every consent version in the snapshot is still the latest and passes the full gate."""
    project = approval.localization.project
    language = approval.localization.target_locale.split("-")[0]
    out = []
    for sc in approval.snapshot["scenes"]:
        for c in sc["consent_versions"]:
            cons = Consent.objects.select_related("identity_owner").get(pk=c["consent_id"])
            check, reason = consent.evaluate(cons.identity_owner, Use.VOICE_SYNTHESIS, project, language)
            if check is None or check.consent_id != cons.pk:
                out.append(f"Consent for {cons.identity_owner} is no longer valid ({reason or 'changed'}).")
    return sorted(set(out))


def request_export(actor, localization):
    require_role(actor, localization.project, Role.LOCALIZATION_MANAGER)
    with transaction.atomic():
        loc = Localization.objects.select_for_update().get(pk=localization.pk)
        approval = loc.approvals.filter(status="VALID").order_by("-pk").first()
        if approval is None or loc.status not in (Localization.Status.APPROVED, Localization.Status.EXPORTED):
            problems = ["Export needs a valid approval first."]
        else:
            problems = export_problems(approval)
        if not problems:
            export = Export.objects.create(approval=approval)
            jobs.enqueue("build_export", actor=actor, project=loc.project, localization=loc, payload={"export_id": export.pk})
            return export
    audit.record_standalone(actor=actor, action="EXPORT_REFUSED", entity=localization,
                            project_id=localization.project_id, details={"reasons": problems})
    raise ExportRefused(" ".join(problems))


def _fmt_srt(ms):
    h, rem = divmod(ms, 3600000)
    m, rem = divmod(rem, 60000)
    s, ms = divmod(rem, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def _subtitles(translations):
    srt, vtt = [], ["WEBVTT", ""]
    for n, t in enumerate(sorted(translations, key=lambda t: t.segment.start_ms), start=1):
        seg = t.segment
        srt += [str(n), f"{_fmt_srt(seg.start_ms)} --> {_fmt_srt(seg.end_ms)}", t.subtitle_text, ""]
        vtt += [f"{_fmt_srt(seg.start_ms).replace(',', '.')} --> {_fmt_srt(seg.end_ms).replace(',', '.')}", t.subtitle_text, ""]
    return "\n".join(srt), "\n".join(vtt)


def _sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def build_export(job, ctx):
    export = Export.objects.select_related("approval__localization__project").get(pk=job.payload["export_id"])
    approval = export.approval
    loc = approval.localization
    project = loc.project
    video = project.videos.get()
    storage = get_storage()
    translations, synths, renders = _snapshot_objects(approval)
    translations = list(translations.select_related("segment"))
    work = tempfile.mkdtemp(prefix="hl-export-", dir=str(settings.HL_MEDIA_ROOT / "tmp"))
    try:
        ctx.checkpoint("subtitles")
        srt, vtt = _subtitles(translations)
        files = {"subtitles.srt": srt, "subtitles.vtt": vtt}
        script = [{
            "segment_id": t.segment_id, "start_ms": t.segment.start_ms, "end_ms": t.segment.end_ms,
            "source_text": t.segment.source_text, "localized_text": t.subtitle_text, "speech_text": t.speech_text,
            "adaptation_type": t.adaptation_type, "origin": t.origin, "version": t.version, "adapter": t.adapter,
            "model": t.model, "prompt_version": t.prompt_version, "context_inputs": t.context_inputs,
        } for t in sorted(translations, key=lambda t: t.segment.start_ms)]
        files["script.json"] = json.dumps(script, ensure_ascii=False, indent=1)
        checks = CheckResult.objects.filter(segment_translation__in=translations)
        files["quality_report.json"] = json.dumps([{
            "segment_id": c.segment_translation.segment_id, "kind": c.kind, "check_type": c.check_type,
            "status": c.status, "messages": c.detail.get("messages", []), "resolution": c.resolution,
            "override_reason": c.reason if c.resolution else "",
        } for c in checks.select_related("segment_translation")], ensure_ascii=False, indent=1)
        for name, content in files.items():
            with open(os.path.join(work, name), "w", encoding="utf-8") as f:
                f.write(content)

        ctx.checkpoint("video")
        placements = [(storage.local_path(s.audio_key), s.segment.start_ms, s.tempo) for s in synths.select_related("segment")]
        speech = None
        if placements:
            speech = os.path.join(work, "speech.wav")
            media_tools.build_speech_track(placements, video.duration_ms, speech)
        media_tools.mux_final(storage.local_path(video.storage_key), speech, os.path.join(work, "subtitles.srt"),
                              os.path.join(work, "localized_video.mp4"))
        if speech:
            os.unlink(speech)

        names = ["localized_video.mp4", *files]
        manifest = {
            "manifest_format": "hyperlocalize-evidence-v0 [PROPOSED format, Phase 0 §7.4]",
            "generated_at": timezone.now().isoformat(),
            "project": {"id": project.pk, "name": project.name, "source_language": project.source_language,
                        "target_locale": loc.target_locale},
            "source_video_sha256": video.sha256,
            "transcript": {"adapter": video.transcript_adapter, "model": video.transcript_model,
                           "is_mock": video.transcript_is_mock},
            "files": {n: _sha(os.path.join(work, n)) for n in names},
            "approval": {"id": approval.pk, "approver": approval.approver.get_username(),
                         "approved_at": approval.approved_at.isoformat()},
            "providers": sorted({f"{t.adapter}:{t.model}:{t.prompt_version}" for t in translations}
                                | {f"{s.adapter}:{s.model}" for s in synths}),
            "rendering_modes": {str(r.scene_id): r.rendering_modes for r in renders},
            "consent_versions": [c for sc in approval.snapshot["scenes"] for c in sc["consent_versions"]],
            "reviews": [{"scene_id": r.scene_id, "decision": r.decision, "reviewer": r.reviewer.get_username()}
                        for r in loc.reviews.select_related("reviewer").order_by("pk")],
            "synthetic_speech_notice": SYNTHETIC_SPEECH_NOTICE,
        }
        package_key, package_path = storage.new_path(".zip")

        with transaction.atomic():
            owner_ids = sorted({Consent.objects.get(pk=c["consent_id"]).identity_owner_id for c in manifest["consent_versions"]})
            for oid in owner_ids:
                IdentityOwner.objects.select_for_update().get(pk=oid)  # CP9 on save: locked, owners first
            approval.refresh_from_db()
            problems = export_problems(approval)
            if problems:
                os.unlink(package_path) if os.path.exists(package_path) else None
                Export.objects.filter(pk=export.pk).update(status=Export.Status.FAILED, error=" ".join(problems)[:2000])
                audit.record(actor=None, action="EXPORT_REFUSED", entity=export, project_id=project.pk,
                             details={"reasons": problems, "checkpoint": "CP9"})
                return
            manifest["audit_chain_head"] = audit.chain_head()  # inside the export transaction (ADR 0007)
            manifest_bytes = json.dumps(manifest, ensure_ascii=False, indent=1, default=str).encode("utf-8")
            with zipfile.ZipFile(package_path, "w", zipfile.ZIP_DEFLATED) as z:
                for n in names:
                    z.write(os.path.join(work, n), n)
                z.writestr("evidence_manifest.json", manifest_bytes)
            package_sha = storage.finalise(package_key)
            manifest_sha = hashlib.sha256(manifest_bytes).hexdigest()
            Export.objects.filter(pk=export.pk).update(
                status=Export.Status.ACTIVE, package_key=package_key, package_sha256=package_sha,
                manifest=json.loads(manifest_bytes), manifest_sha256=manifest_sha)
            Localization.objects.filter(pk=loc.pk).update(status=Localization.Status.EXPORTED)
            audit.record(actor=approval.approver, action="EXPORT_CREATED", entity=export, project_id=project.pk,
                         consent_version=",".join(f"{c['consent_id']}:v{c['version']}" for c in manifest["consent_versions"]),
                         details={"manifest_sha256": manifest_sha, "package_sha256": package_sha,
                                  "chain_head_seq": manifest["audit_chain_head"]["seq"]})
    finally:
        for n in os.listdir(work):
            os.unlink(os.path.join(work, n))
        os.rmdir(work)


def mark_consent_revoked(localization):
    """Revocation cascade: ACTIVE exports of this localization are blocked (ADR 0006 §5, §7)."""
    for export in Export.objects.select_for_update().filter(approval__localization=localization, status=Export.Status.ACTIVE):
        export.status = Export.Status.CONSENT_REVOKED
        export.save(update_fields=["status"])
        audit.record(actor=None, action="EXPORT_CONSENT_REVOKED", entity=export, project_id=localization.project_id,
                     details={"package_sha256": export.package_sha256})


def purge_revoked_exports(project):
    """Delete package files of exports blocked by revocation (ADR 0020 §5). Copies already
    downloaded cannot be recalled (ADR 0006 §7)."""
    storage = get_storage()
    purged = []
    for export in Export.objects.filter(approval__localization__project=project, status=Export.Status.CONSENT_REVOKED):
        storage.delete(export.package_key)
        Export.objects.filter(pk=export.pk).update(status=Export.Status.PURGED)
        purged.append(export.pk)
    return purged


def can_download(export):
    """CP10: serve only ACTIVE exports whose consent still holds."""
    if export.status != Export.Status.ACTIVE:
        return False, "This export is no longer available (consent revoked or purged)."
    if export.approval.status != export.approval.Status.VALID:
        return False, "The approval behind this export was invalidated."
    problems = _consent_problems(export.approval)
    return (not problems), " ".join(problems)
