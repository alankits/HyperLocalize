"""Generate the UML class diagram (Mermaid) from the ACTUAL Django models, so the diagram cannot
contain invented classes or drift from the code. Usage: .venv/bin/python scripts/generate_uml.py"""
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "hyperlocalize.settings")
import django  # noqa: E402

django.setup()
from django.apps import apps  # noqa: E402
from django.db import models  # noqa: E402

APPS = ["accounts", "projects", "localization", "rendering", "review", "identity", "exports", "audit", "pipeline"]
SKIP_FIELDS = {"password", "last_login", "is_superuser", "is_staff", "date_joined", "first_name", "last_name", "email"}


def field_type(f):
    if isinstance(f, models.JSONField):
        return "json"
    return f.get_internal_type().replace("Field", "").replace("BigAuto", "id").replace("Auto", "id")


def main():
    lines = ["```mermaid", "classDiagram", "  direction LR"]
    rels = []
    for label in APPS:
        lines.append(f"  namespace {label} {{")
        for model in apps.get_app_config(label).get_models():
            name = model.__name__
            lines.append(f"    class {name} {{")
            for f in model._meta.get_fields():
                if f.auto_created and not f.concrete:
                    continue
                if f.name in SKIP_FIELDS or f.name in ("groups", "user_permissions"):
                    continue
                if f.is_relation and f.concrete or isinstance(f, models.ManyToManyField):
                    target = f.related_model.__name__
                    if f.many_to_many:
                        rels.append(f"  {name} \"*\" --> \"*\" {target} : {f.name}")
                    elif f.one_to_one:
                        rels.append(f"  {name} \"0..1\" --> \"{'0..1' if f.null else '1'}\" {target} : {f.name}")
                    else:
                        rels.append(f"  {name} \"*\" --> \"{'0..1' if f.null else '1'}\" {target} : {f.name}")
                    continue
                if f.concrete:
                    lines.append(f"      +{field_type(f)} {f.name}")
            lines.append("    }")
        lines.append("  }")
    lines += rels + ["```"]
    out = Path(__file__).resolve().parent.parent / "docs" / "uml" / "class_diagram.md"
    header = ("# UML class diagram (generated from the code)\n\n"
              "Generated by `scripts/generate_uml.py` from the actual Django models. Do not edit by hand: rerun the script.\n"
              "Relationship labels are the foreign-key field names; multiplicities come from `null` on the field.\n\n")
    out.write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
